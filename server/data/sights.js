/** 将紧凑行展开为标准景点对象 */
function expandRow(row) {
  const [name, rating, popularity, type, ticket, openTime, visitHours, address, desc, tagStr] = row;
  return {
    name,
    rating,
    popularity,
    type,
    ticket,
    openTime,
    visitHours,
    address,
    desc,
    tags: tagStr ? tagStr.split(/\s+/).filter(Boolean) : [],
    recommended: popularity >= 88,
    photo: null,
    location: null,
  };
}

/** 按城市名取内置景点列表（找不到返回空数组） */
function getSightsByCity(cityName) {
  const rows = SIGHTS[cityName] || [];
  return rows.map(expandRow);
}

